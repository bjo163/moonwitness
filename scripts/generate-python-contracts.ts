#!/usr/bin/env tsx

/**
 * ◈ MOONWITNESS — PYTHON CONTRACT GENERATOR
 *
 * Derives strongly-typed Python Pydantic v2 data models directly from
 * contracts/openapi/openapi.json for all services in services/*
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')
const contractPath = path.join(rootDir, 'contracts', 'openapi', 'openapi.json')

if (!fs.existsSync(contractPath)) {
  console.error(`❌ Contract file not found at: ${contractPath}`)
  console.error(`Run 'pnpm contracts:export' first.`)
  process.exit(1)
}

const spec = JSON.parse(fs.readFileSync(contractPath, 'utf8'))
const allSchemas: Record<string, any> = { ...(spec.components?.schemas || {}) }

// Extract custom microservice contracts from OpenAPI paths
const paths = spec.paths || {}
if (paths['/api/services/celestial/qibla']?.get?.responses?.['200']?.content?.['application/json']?.schema) {
  allSchemas['QiblaCalculationResult'] = paths['/api/services/celestial/qibla'].get.responses['200'].content['application/json'].schema
}

const hilalSchema = paths['/api/services/celestial/hilal-visibility']?.get?.responses?.['200']?.content?.['application/json']?.schema
if (hilalSchema?.properties) {
  if (hilalSchema.properties.mabims_criterion) {
    allSchemas['MabimsCriterion'] = hilalSchema.properties.mabims_criterion
    hilalSchema.properties.mabims_criterion = { $ref: '#/components/schemas/MabimsCriterion' }
  }
  if (hilalSchema.properties.odeh_criterion) {
    allSchemas['OdehCriterion'] = hilalSchema.properties.odeh_criterion
    hilalSchema.properties.odeh_criterion = { $ref: '#/components/schemas/OdehCriterion' }
  }
  allSchemas['HilalVisibilityEvaluation'] = hilalSchema
}

const aiSearchBody = paths['/api/services/ai/semantic/search']?.post?.requestBody?.content?.['application/json']?.schema
if (aiSearchBody) {
  allSchemas['SemanticSearchRequest'] = aiSearchBody
}

const aiSearchRes = paths['/api/services/ai/semantic/search']?.post?.responses?.['200']?.content?.['application/json']?.schema
if (aiSearchRes?.properties) {
  if (aiSearchRes.properties.results?.items) {
    allSchemas['SemanticSearchHit'] = aiSearchRes.properties.results.items
    aiSearchRes.properties.results.items = { $ref: '#/components/schemas/SemanticSearchHit' }
  }
  allSchemas['SemanticSearchResult'] = aiSearchRes
}

const prayerTimesRes = paths['/api/services/celestial/prayer-times']?.get?.responses?.['200']?.content?.['application/json']?.schema
if (prayerTimesRes) {
  allSchemas['CelestialPrayerTimesResult'] = prayerTimesRes
}

const hybridSearchBody = paths['/api/services/ai/semantic/hybrid-search']?.post?.requestBody?.content?.['application/json']?.schema
if (hybridSearchBody) {
  allSchemas['HybridSearchRequest'] = hybridSearchBody
}

const hybridSearchRes = paths['/api/services/ai/semantic/hybrid-search']?.post?.responses?.['200']?.content?.['application/json']?.schema
if (hybridSearchRes?.properties) {
  if (hybridSearchRes.properties.results?.items) {
    allSchemas['HybridSearchHit'] = hybridSearchRes.properties.results.items
    hybridSearchRes.properties.results.items = { $ref: '#/components/schemas/HybridSearchHit' }
  }
  allSchemas['HybridSearchResult'] = hybridSearchRes
}

const lines: string[] = [

  '# ◈ AUTO-GENERATED BY MOONWITNESS UNIVERSAL CONTRACT TYPEGEN',
  '# DO NOT EDIT DIRECTLY. Run `pnpm contracts:generate:python` to update.',
  '# Generated from: contracts/openapi/openapi.json',
  '',
  'from __future__ import annotations',
  'from typing import Optional, List, Dict, Any',
  'from pydantic import BaseModel',
  '',
  '',
]

function toPythonType(prop: any, required: boolean): string {
  if (!prop) return required ? 'Any' : 'Optional[Any] = None'
  let pyType = 'Any'
  if (prop.type === 'string') pyType = 'str'
  else if (prop.type === 'number') pyType = 'float'
  else if (prop.type === 'integer') pyType = 'int'
  else if (prop.type === 'boolean') pyType = 'bool'
  else if (prop.type === 'array') {
    const itemType = toPythonType(prop.items, true)
    pyType = `List[${itemType}]`
  } else if (prop.type === 'object') {
    pyType = 'Dict[str, Any]'
  } else if (prop.$ref) {
    const refName = prop.$ref.split('/').pop()
    pyType = refName || 'Any'
  }

  return required ? pyType : `Optional[${pyType}] = None`
}

for (const [name, schema] of Object.entries<any>(allSchemas)) {
  lines.push(`class ${name}(BaseModel):`)
  const props = schema.properties || {}
  const requiredList: string[] = schema.required || []
  const propEntries = Object.entries(props)

  if (propEntries.length === 0) {
    lines.push('    pass')
  } else {
    // Sort required fields first, then optional fields
    const sorted = [...propEntries].sort(([a], [b]) => {
      const aReq = requiredList.includes(a) ? 0 : 1
      const bReq = requiredList.includes(b) ? 0 : 1
      return aReq - bReq
    })

    for (const [propName, propDef] of sorted) {
      const isReq = requiredList.includes(propName)
      const typeStr = toPythonType(propDef, isReq)
      lines.push(`    ${propName}: ${typeStr}`)
    }
  }
  lines.push('')
  lines.push('')
}

const content = lines.join('\n')

const destinations = [
  path.join(rootDir, 'services', 'celestial-engine', 'src', 'models', 'contracts.py'),
  path.join(rootDir, 'services', 'ai-agent', 'src', 'models', 'contracts.py'),
]

for (const dest of destinations) {
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, content, 'utf8')
  console.log(`✅ Pydantic contract models generated: ${path.relative(rootDir, dest)}`)
}
